// Combined native checks selected from the preauthored menu/book/action/state scenarios.
// Fixtures: furnace12,-60,1, chest12,-60,2, table11,-60,3, anvil14,-60,3;
// chest ore1/coal1/lapis3/iron sword1/emerald2/named writable book1; native XP1515.
const assert=(value,message)=>{if(!value)throw new Error(message);};
const id=name=>bot.registry.itemsByName[name].id;
const out={};
assert(bot.experience.points===1515,'Native saved XP plus fixture orb differs');
assert(typeof bot.time.bigTime==='bigint' && bot.health===20 && Number.isFinite(bot.oxygenLevel),'Native state missing');
assert(bot.supportFeature('doesNotExist')===false,'Unknown version feature');
const clock=bot.time, age=clock.bigAge; await bot.waitForTicks(2);
assert(bot.time===clock && clock.bigAge>age,'Time hydration/identity');
out.state={health:bot.health,air:bot.oxygenLevel,age:String(clock.bigAge),xp:bot.experience.points};
const chest=await bot.openContainer(bot.blockAt(new Vec3(12,-60,2)));
for(const [name,count] of [['iron_ore',1],['coal',1],['lapis_lazuli',3],['iron_sword',1],['emerald',2],['writable_book',1]]) await chest.withdraw(id(name),null,count);
await chest.close();
const furnace=await bot.openFurnace(bot.blockAt(new Vec3(12,-60,1)));
assert(furnace.fuel===0 && furnace.progress===0 && !furnace.inputItem(),'Initial furnace fields');
let updates=0;furnace.on('update',()=>updates++);
await furnace.putInput(id('iron_ore'),null,1);await furnace.putFuel(id('coal'),null,1);
for(let ticks=0;!furnace.outputItem() && ticks<240;ticks++) await bot.waitForTicks(1);
assert(furnace.outputItem()?.name==='iron_ingot' && updates>0,'Native smelting failed');
out.furnace={output:(await furnace.takeOutput()).name,updates};await furnace.close();console.log('Furnace passed');
let book=bot.inventory.items().find(i=>i.name==='writable_book');
const slot=book.slot,selected=bot.quickBarSlot;
await bot.writeBook(slot,['Native page','Second page']);
assert(bot.inventory.slots[slot]?.name==='writable_book' && bot.quickBarSlot===selected,'Book write restoration');
await bot.signBook(slot,['Native page','Second page'],'Ignored client author','Native port');
book=bot.inventory.slots[slot];
assert(book?.name==='written_book' && bot.quickBarSlot===selected && !bot.inventory.selectedItem,'Book sign restoration');
out.book={slot,components:book.components};console.log('Book passed');
const anvil=await bot.openAnvil(bot.blockAt(new Vec3(14,-60,3)));
await anvil.rename(bot.inventory.items().find(i=>i.name==='iron_ingot'),'Script metal');await anvil.close();
const ingot=bot.inventory.items().find(i=>i.name==='iron_ingot');
assert(ingot?.customName,'Native anvil name missing');out.anvil={name:ingot.customName,xp:bot.experience.points};console.log('Anvil passed');
const enchant=await bot.openEnchantmentTable(bot.blockAt(new Vec3(11,-60,3)));
await enchant.putTargetItem(bot.inventory.items().find(i=>i.name==='iron_sword'));
await enchant.putLapis(bot.inventory.items().find(i=>i.name==='lapis_lazuli'));
assert(enchant.enchantments[0].level>0,'Native enchantment options missing');
const enchanted=await enchant.enchant(0);assert(enchanted.components.some(c=>c.type==='enchantments'),'Native enchantments missing');
await enchant.takeTargetItem();await enchant.close();out.enchantment={components:enchanted.components,xp:bot.experience.points};console.log('Enchant passed');
const villager=Object.values(bot.entities).find(e=>e.name==='villager');
const trade=await bot.openVillager(villager);const used=trade.trades[0].nbTradeUses;
await trade.trade(0,2);assert(trade.trades[0].nbTradeUses===used+2,'Native trade uses');await trade.close();
assert(bot.inventory.count(id('apple'))===4 && bot.inventory.count(id('emerald'))===0,'Native trade items');out.trade={apples:4,uses:used+2};console.log('Trade passed');
await bot.look(0,0,true);assert(Math.abs(bot.entity.pitch)<0.001,'Native look pitch');
await bot.lookAt(new Vec3(15.5,-59.5,4.5),false);
await bot.equip(bot.inventory.items().find(i=>i.name==='diamond_pickaxe'),'hand');
const stone=bot.blockAt(new Vec3(15,-60,4));assert(bot.canDigBlock(stone) && Number.isFinite(bot.digTime(stone)),'Native mining predicate');
await bot.dig(stone);assert(bot.blockAt(stone.position).name==='air','Native dig state');
await bot.equip(bot.inventory.items().find(i=>i.name==='stone'),'hand');
await bot.placeBlock(bot.blockAt(new Vec3(15,-61,5)),new Vec3(0,1,0));
assert(bot.blockAt(new Vec3(15,-60,5)).name==='stone','Native placement state');
out.actions={dug:true,placed:true,position:bot.entity.position};
assert(!bot.currentWindow && !bot.inventory.selectedItem,'Final menu/cursor');
return out;
